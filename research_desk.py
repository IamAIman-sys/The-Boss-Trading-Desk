def load(folder, name):
    path = folder / name
    if not path.is_file():
        raise data.DeskError(f"Missing {name}; complete the required data steps first.")
    return json.loads(path.read_text(encoding="utf-8"))


def source_lines(text, label, start=0):
    return [{"source": label, "line": i + start + 1, "text": line}
            for i, line in enumerate(text.splitlines())]


def research_excerpts(text, items=("1", "7"), label="10-K"):
    """Choose the longest Business and MD&A section, avoiding table-of-contents hits."""
    lines = text.splitlines()
    headings = []
    for i, line in enumerate(lines):
        match = re.match(r"^\s*Item\s+(\d+[A-C]?)\b", line, re.I)
        if match:
            headings.append((i, match[1].upper()))
    result = []
    for item in items:
        spans = []
        for n, (start, number) in enumerate(headings):
            if number == item:
                end = headings[n + 1][0] if n + 1 < len(headings) else len(lines)
                spans.append((sum(len(line) for line in lines[start:end]), start, end))
        if not spans:
            raise data.DeskError(f"Could not locate {label} Item {item}; inspect the filing's headings.")
        _, start, end = max(spans)
        used = 0
        for i in range(start, end):
            if used + len(lines[i]) > 25000:
                break
            result.append({"source": label, "line": i + 1, "text": lines[i]})
            used += len(lines[i])
    return result


def table_numbers(line):
    numbers = []
    for cell in line.split("|")[1:]:
        cleaned = cell.strip().replace(",", "").replace("$", "").strip()
        if re.fullmatch(r"\(?-?\d+(?:\.\d+)?\)?", cleaned):
            if cleaned.startswith("(") and cleaned.endswith(")"):
                cleaned = "-" + cleaned[1:-1]
            numbers.append(Decimal(cleaned))
    return numbers


def quarterly_facts(release, accession, exhibit_label="Exhibit 99.1"):
    """Parse only matched, numeric table rows. Ambiguity is reported, not guessed."""
    lines = release.splitlines()
    matches = data.release_lines(release)
    statement_starts = [i for i, line in enumerate(lines) if re.search(
        r"consolidated\s+statements?\s+(?:of\s+)?(?:operations|income|earnings)", line, re.I)]
    statement_ranges = []
    for start in statement_starts:
        end = next((i for i in range(start + 1, len(lines)) if re.search(
            r"consolidated\s+(?:balance|statements?\s+(?:of\s+)?(?:cash|operations|income|earnings))", lines[i], re.I)), len(lines))
        statement_ranges.append((start, end))
    output = {"accession": accession, "exhibit_label": exhibit_label}
    for concept in ("total_revenue", "diluted_eps"):
        candidates = []
        for match in matches[concept]:
            if statement_ranges and not any(start <= match["line_number"] - 1 < end for start, end in statement_ranges):
                continue
            if "|" not in match["line"]:
                continue
            values = table_numbers(match["line"])
            if len(values) < 2:
                continue
            i = match["line_number"] - 1
            before = lines[max(0, i - 45):i]
            # Require a recognizable quarter-first table header, not YTD-only data.
            headers = [line for line in before if re.search(r"(?:three\s+months|1[2-7]\s+weeks|quarter)\s+ended", line, re.I)]
            if not headers:
                continue
            first = re.search(r"(?:three|six|nine|twelve|\d+)\s+(?:months|weeks)|quarter|year", headers[-1], re.I)
            if not first or not re.fullmatch(r"three\s+months|1[2-7]\s+weeks|quarter", first[0], re.I):
                continue
            # Avoid reconciliation tables and explicitly adjusted measures.
            if re.search(r"adjusted|non.gaap", match["line"], re.I):
                continue
            unit = "USD/share" if concept == "diluted_eps" else "as printed in source"
            if concept == "total_revenue":
                for line in reversed(before):
                    unit_match = re.search(r"(?:in|dollars\s+in)\s+(millions|thousands|billions)", line, re.I)
                    if unit_match:
                        unit = "USD " + unit_match[1].lower()
                        break
            candidates.append({"current": str(values[0]), "prior": str(values[1]),
                               "unit": unit, "source": match, "period_header": headers[-1],
                               "column_dates": next((line for line in before[before.index(headers[-1]) + 1:]
                                                      if re.search(r"\b20\d{2}\b", line)), "See source table")})
        distinct = {(entry["current"], entry["prior"], entry["unit"]) for entry in candidates}
        output[concept] = candidates[0] if len(distinct) == 1 else {
            "missing": "No unambiguous quarter-first table row; inspect the release manually."}
    revenue = output["total_revenue"]
    if "missing" not in revenue and Decimal(revenue["prior"]) != 0:
        current, prior = Decimal(revenue["current"]), Decimal(revenue["prior"])
        output["revenue_growth"] = {"value": str((current - prior) / prior * 100),
                                    "arithmetic": f"({data.fmt(current)} - {data.fmt(prior)}) / {data.fmt(prior)} * 100",
                                    "unit": "%"}
    else:
        output["revenue_growth"] = {"missing": "Quarterly revenue inputs missing or prior revenue is zero."}
    return output


def calculator_inputs(facts):
    return {prefix + key: str(item[column]["val"])
            for key, item in facts["facts"].items()
            for column, prefix in (("current", ""), ("prior", "prior_")) if item[column] is not None}


def safe_calculate(expression, inputs):
    """Only arithmetic on known fact names and a short list of constants."""
    if len(expression) > 250:
        raise ValueError("Expression is too long.")
    tree = ast.parse(expression, mode="eval")
    def visit(node):
        if isinstance(node, ast.Expression):
            return visit(node.body)
        if isinstance(node, ast.Name) and node.id in inputs:
            return Decimal(inputs[node.id]), data.fmt(inputs[node.id])
        if isinstance(node, ast.Constant) and type(node.value) is int and node.value in (0, 1, 2, 100):
            return Decimal(node.value), str(node.value)
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
            val, text = visit(node.operand)
            return -val, f"-({text})"
        if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Sub, ast.Mult, ast.Div)):
            left, lt = visit(node.left)
            right, rt = visit(node.right)
            if isinstance(node.op, ast.Add):
                return left + right, f"({lt} + {rt})"
            if isinstance(node.op, ast.Sub):
                return left - right, f"({lt} - {rt})"
            if isinstance(node.op, ast.Mult):
                return left * right, f"({lt} * {rt})"
            if right == 0:
                raise ValueError("Denominator is zero.")
            return left / right, f"({lt} / {rt})"
        raise ValueError("Use only available fact names, arithmetic and constants 0, 1, 2, 100.")
    value, arithmetic = visit(tree)
    return {"value": str(value), "arithmetic": arithmetic, "expression": expression}


def fact_citation(entry):
    period = f"{entry['start']} to {entry['end']}" if entry.get("start") else entry["end"]
    return f"{entry['accn']}, `{entry['tag']}`, {period}"


def section_body(body, title):
    """The compiler owns the five headings; remove a role's repeated heading."""
    return re.sub(r"^\s*#{1,3}\s+" + re.escape(title) + r"\s*\n+", "", body).strip()


def evidence_markdown(facts, calculations, quarter, peers):
    lines = ["### Python evidence for the financial analysis", "",
             "All annual amounts use the fiscal periods below. Missing values are not zero.", "",
             "| Annual fact | Current year | Prior year |", "| --- | --- | --- |"]
    for item in facts["facts"].values():
        cells = []
        for column in ("current", "prior"):
            entry = item[column]
            cells.append(f"{data.fmt(entry['val'])} {entry['unit']}; {fact_citation(entry)}" if entry else "Missing")
        lines.append(f"| {item['label']} | {cells[0]} | {cells[1]} |")
    lines += ["", "Definitions: operating margin uses total revenue; ROE uses the average of the two annual equity balances. "
              "Debt includes its current portion. Free cash flow is cash from operations minus additions to PP&E. "
              "P/E = the supplied share price / latest fiscal-year GAAP diluted EPS. "
              "This uses annual EPS, not quarterly, trailing-twelve-month, or forward EPS.", ""]
    if calculations.get("price_reference"):
        reference = calculations["price_reference"]
        lines += [f"Price input: {calculations['price_usd']} USD/share; date: {reference['date']}; "
                  f"source supplied with the run: {reference['source']}. The reader should check that source.", ""]
        if reference.get("provider"):
            lines += [f"Fetched from {reference['provider']}; field: {reference['field']}; "
                      f"retrieved: {reference['retrieved_at']}. {reference['adjustment']} "
                      f"{reference.get('currency_basis', '')}", ""]
    else:
        lines += ["The supplied price's market date and source have not been confirmed.", ""]
    for label, row in calculations["calculations"].items():
        if row["value"] is None:
            lines.append(f"- {label}: missing ({row['reason']}).")
        else:
            lines.append(f"- {label}: {row['arithmetic']} = {data.fmt(row['value'])} {row['unit']}. Inputs: annual facts above.")
        if row.get("definition"):
            lines.append("  Definition: " + row["definition"])
    lines += ["", "### Latest reported quarter", ""]
    for key, label in (("total_revenue", "Total revenue"), ("diluted_eps", "GAAP diluted EPS")):
        entry = quarter[key]
        if "missing" in entry:
            lines.append(f"- {label}: missing. {entry['missing']}")
        else:
            source = entry["source"]
            lines.append(f"- {label}: {data.fmt(entry['current'])} {entry['unit']}; prior-year quarter: "
                         f"{data.fmt(entry['prior'])} {entry['unit']}. {quarter['accession']}, "
                         f"{quarter['exhibit_label']} L{source['line_number']}; table header: {entry['period_header']}; "
                         f"column dates: {entry['column_dates']}.")
            lines.append(f"  Source quote: {source['line']}")
    growth = quarter["revenue_growth"]
    lines.append("- Quarterly revenue growth: " + (growth["missing"] if "missing" in growth else
                 f"{growth['arithmetic']} = {data.fmt(growth['value'])}%. Inputs: the two release revenue columns above."))
    lines += ["", "### Peer operating margins", ""]
    for ticker, peer in peers.items():
        if "error" in peer:
            lines.append(f"- {ticker}: unavailable ({peer['error']}).")
            continue
        margin = peer["operating_margin"]
        pf = peer["facts"]["facts"]
        if margin["value"] is None:
            lines.append(f"- {ticker}: unavailable ({margin['reason']}).")
        else:
            lines.append(f"- {ticker}: {margin['arithmetic']} = {data.fmt(margin['value'])}%. "
                         f"Operating income: {fact_citation(pf['operating_income']['current'])}; "
                         f"total revenue: {fact_citation(pf['revenue']['current'])}.")
    if not peers:
        lines.append("No peers supplied.")
    return "\n".join(lines)


class ReportManager:
    def __init__(self, client, folder):
        self.client, self.folder = client, folder
        self.trace = []

    def call(self, role, context, correction=None):
        print(f"Role: {role}" + (" (revision)" if correction else ""), flush=True)
        payload = {"task": f"Perform the {role} task.", "context": context,
                   "expected_output": "JSON object in the schema specified by your role instructions."}
        if correction:
            payload["task"] += " Correction requested by Strategy Manager: " + correction
        result = self.client.complete(INSTRUCTIONS[role], payload)
        self.trace.append({"role": role, "request": payload, "result": result,
                           "metadata": self.client.last_metadata,
                           "time": datetime.now().astimezone().isoformat()})
        data.save_json(self.folder / "role_calls.json", self.trace)
        return result

    def financial(self, context, correction=None):
        result = self.call("Financial Analyst", context, correction)
        if result.get("calculator_requests"):
            requests = result["calculator_requests"]
            if not isinstance(requests, list) or len(requests) > 4:
                raise ModelError("Financial Analyst requested more than 4 calculator expressions.")
            outputs = []
            for request in requests:
                try:
                    outputs.append({"name": request["name"], **safe_calculate(request["expression"], context["available_calculator_inputs"])})
                except (KeyError, ValueError, SyntaxError, ArithmeticError) as exc:
                    outputs.append({"name": request.get("name", "unnamed"), "error": str(exc)})
            result = self.call("Financial Analyst", {**context, "calculator_results": outputs,
                                                     "calculator_rounds_remaining": 0}, correction)
            if result.get("calculator_requests"):
                raise ModelError("Financial Analyst exceeded the one-round calculator limit.")
            data.save_json(self.folder / "extra_calculations.json", outputs)
        return result

    def run(self):
        data.save_json(self.folder / "report_status.json", {"status": "running", "model": self.client.model,
                                                            "human_audit": "pending"})
        manifest = load(self.folder, "manifest.json")
        for number in (1, 2, 3, 4, 5, 6, 7):
            if manifest["steps"].get(str(number), {}).get("status") != "complete":
                raise data.DeskError(f"Data step {number} is incomplete or stale. Complete it before the model report.")
        selected = load(self.folder, "selected_filings.json")
        facts = load(self.folder, "facts.json")
        calculations = load(self.folder, "calculations.json")
        peers = load(self.folder, "peers.json")
        release = (self.folder / "earnings_release.txt").read_text(encoding="utf-8")
        exhibit_label = load(self.folder, "documents.json")["earnings_release"].get("exhibit_label", "Exhibit 99.1")
        quarter = quarterly_facts(release, selected["8-K"]["accessionNumber"], exhibit_label)
        data.save_json(self.folder / "quarter_facts.json", quarter)
        evidence = evidence_markdown(facts, calculations, quarter, peers)
        filing_info = {form: {k: row[k] for k in ("accessionNumber", "accepted", "index_url", "document_url")}
                       for form, row in selected.items()}
        research_context = {"company": manifest["company"], "filings": filing_info,
                            "excerpt_policy": "At most the first 25,000 characters of each Business/MD&A section, on complete lines. Full texts are retained for audit.",
                            "10-K_excerpts": research_excerpts((self.folder / "10-K.txt").read_text(encoding="utf-8")),
                            "release": source_lines(release, exhibit_label)}
        financial_context = {"company": manifest["company"], "facts": facts, "calculations": calculations,
                             "quarter": quarter, "peers": peers, "financial_evidence_markdown": evidence,
                             "10-Q_MD&A": research_excerpts((self.folder / "10-Q.txt").read_text(encoding="utf-8"),
                                                            items=("2",), label="10-Q"),
                             "available_calculator_inputs": calculator_inputs(facts)}
        research = self.call("Research Analyst", research_context)
        financial = self.financial(financial_context)

        def advisor_context():
            return {"Research Analyst": research, "Financial Analyst": {
                **financial, "python_financial_evidence": evidence}}

        advisor = self.call("Investment Advisor", advisor_context())

        def assembled():
            combined = {part: "" for part in PARTS}
            for role, result in (("Research Analyst", research), ("Financial Analyst", financial),
                                 ("Investment Advisor", advisor)):
                for section, owner in OWNERS.items():
                    if owner == role:
                        sections = result.get("sections", {})
                        body = sections.get(section, "") if isinstance(sections, dict) else ""
                        combined[section] = section_body(body, section) if isinstance(body, str) else ""
            if combined[PARTS[2]]:
                combined[PARTS[2]] += "\n\n" + evidence
            if combined[PARTS[4]]:
                combined[PARTS[4]] += (
                    "\n\nRecommendation: " + str(advisor.get("recommendation", "Missing"))
                    + "\n\nDeciding number: " + str(advisor.get("deciding_number", "Missing")))
            return combined

        def review():
            sections = assembled()
            result = self.call("Strategy Manager", {"sections": sections, "analyst_outputs": advisor_context(),
                                                     "research_evidence": research_context,
                                                     "financial_evidence_markdown": evidence,
                                                     "quarter_sources": quarter,
                                                     "required_core_claims": CORE_CLAIMS,
                                                     "section_owners": OWNERS,
                                                     "required_parts": PARTS})
            revisions = result.get("revisions", [])
            if not isinstance(revisions, list):
                raise ModelError("Manager revisions must be a list.")
            for section, body in sections.items():
                if not isinstance(body, str) or not body.strip():
                    revisions.append({"role": OWNERS[section], "reason": f"Missing required section: {section}"})
            if advisor.get("recommendation") not in {"Buy", "Hold", "Sell"} or not advisor.get("deciding_number"):
                revisions.append({"role": "Investment Advisor", "reason": "Supply Buy/Hold/Sell and one sourced deciding number."})
            return result, revisions

        review_result, revisions = review()
        if revisions:
            reasons = {}
            for revision in revisions:
                role = revision.get("role")
                if role not in {"Research Analyst", "Financial Analyst", "Investment Advisor"}:
                    raise ModelError("Manager requested an unknown revision role.")
                reasons.setdefault(role, []).append(str(revision.get("reason", "Check your output.")))
            if "Research Analyst" in reasons:
                research = self.call("Research Analyst", research_context, "; ".join(reasons["Research Analyst"]))
            if "Financial Analyst" in reasons:
                financial = self.financial(financial_context, "; ".join(reasons["Financial Analyst"]))
            # Recheck the recommendation once if either upstream role changed.
            advisor = self.call("Investment Advisor", advisor_context(),
                                "; ".join(reasons.get("Investment Advisor", ["Reconcile the updated analyst outputs."])))
            review_result, revisions = review()
        now = datetime.now().astimezone().isoformat()
        first_line = f"{manifest['company']['name']} ({manifest['company']['ticker']}); filings read: " + "; ".join(
            f"{form} {row['accessionNumber']} ({'primary document and ' + exhibit_label if form == '8-K' else 'primary document'})"
            for form, row in selected.items())
        lines = [first_line, "Report run time: " + now, "",
                 f"Model: `{self.client.model}` via Purdue GenAI Studio.",
                 "Status: DRAFT — human audit and partner checks are pending.",
                 f"The model roles used 10-K Business/MD&A excerpts, 10-Q MD&A excerpts, annual XBRL facts, and {exhibit_label}.", ""]
        for part, body in assembled().items():
            lines.extend(["## " + part, "", body or "MISSING", ""])
        issues = review_result.get("issues", [])
        if revisions or issues:
            lines.extend(["## Remaining review items", ""])
            lines.extend("- " + str(item) for item in issues)
            lines.extend("- " + str(item.get("reason", item)) for item in revisions)
        lines.extend(["", "This is a learning exercise, not financial advice.",
                      f"AI assistance: Codex and Purdue GenAI Studio ({self.client.model}).",
                      "Human source verification and sign-off are pending. This draft must not be presented as audited.", ""])
        path = self.folder / ("report_draft.md" if revisions else "report.md")
        path.write_text("\n".join(lines), encoding="utf-8")
        data.save_json(self.folder / "report_status.json", {"status": "draft" if revisions else "generated",
                       "model": self.client.model, "run_time": now,
                       "report": path.name, "human_audit": "pending", "manager_revisions_remaining": revisions,
                       "manager_issues": issues, "model_calls": len(self.trace)})
        print("Report:", path)
        if revisions:
            raise ModelError("Report saved as report_draft.md; manager issues remain after one revision round.")
        return path


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ticker", type=data.normalize_ticker)
    parser.add_argument("--peers", nargs="*", default=[])
    parser.add_argument("--price", type=data.positive_price)
    parser.add_argument("--price-date", help="Date of the supplied price, YYYY-MM-DD")
    parser.add_argument("--price-source", help="Source URL for the supplied price")
    parser.add_argument("--reuse", action="store_true", help="Use the latest completed saved data run; do not fetch SEC data")
    fd.add_arguments(parser)
    args = parser.parse_args(argv)
    run = None
    try:
        provider_options = fd.options(args)
        if bool(args.price_date) != bool(args.price_source) or (args.price_date and args.price is None):
            raise data.DeskError("Use --price-date and --price-source together with --price.")
        if args.price_date:
            date.fromisoformat(args.price_date)
            if not args.price_source.startswith("https://"):
                raise data.DeskError("Price source must be an HTTPS URL.")
        peers = list(dict.fromkeys(data.normalize_ticker(t) for group in args.peers for t in group.split(",") if t))
        client = ModelClient()
        run = data.Desk(data.SECClient(), args.ticker, peers, args.price, 5 if args.reuse else None,
                        **provider_options)
        if not args.reuse:
            for step in range(1, 8):
                run.run_step(step)
        else:
            if peers:
                saved_peers = load(run.folder, "peers.json")
                if set(peers) != set(saved_peers):
                    raise data.DeskError("Requested peers differ from the saved run; rerun data step 7 or omit --reuse.")
            if args.price is not None or args.fetch_price_date:
                run.run_step(5)
            if args.compare_financial_datasets:
                run.compare_facts(run.require("facts.json", 4), run.folder)
                saved_peers = run.require("peers.json", 7)
                for ticker, peer in saved_peers.items():
                    if "facts" not in peer:
                        raise data.DeskError(f"Saved peer facts are missing for {ticker}.")
                    run.compare_facts(peer["facts"], run.folder / "peers" / ticker)
            print("Using saved data:", run.folder, flush=True)
        if args.price_date:
            calculations = load(run.folder, "calculations.json")
            calculations["price_reference"] = {"date": args.price_date, "source": args.price_source}
            data.save_json(run.folder / "calculations.json", calculations)
            data.save_json(run.folder / "price_reference.json", calculations["price_reference"])
        ReportManager(client, run.folder).run()
        return 0
    except (data.DeskError, ModelError, OSError, ValueError, argparse.ArgumentTypeError) as exc:
        if run and run.folder:
            status_path = run.folder / "report_status.json"
            status = json.loads(status_path.read_text()) if status_path.exists() else {}
            status.update({"status": "failed", "error": str(exc), "human_audit": "pending"})
            data.save_json(status_path, status)
        print("ERROR:", exc, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
